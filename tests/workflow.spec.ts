import { expect, test } from '@playwright/test'

test('shares a selected journal excerpt in chat and revokes future access', async ({ page }) => {
  await page.goto('./#/student/messages?id=chat-fah')
  await page.getByRole('button', { name: 'เลือกสิ่งที่จะแบ่งปัน' }).click()
  const picker = page.getByRole('dialog', { name: 'เลือกสิ่งที่จะแบ่งปัน' })
  await picker.getByLabel('ประเภทข้อมูล').selectOption('journal')
  await picker.getByLabel('เลือกบันทึก').selectOption('journal-2')
  await picker.getByLabel('คัดลอกเฉพาะส่วนที่อยากส่ง').fill('เป็นช่วงเงียบ ๆ')
  await picker.getByRole('button', { name: 'แนบไว้ตรวจสอบก่อนส่ง' }).click()
  await expect(page.getByText('ตรวจสิ่งที่จะแบ่งปันกับ ครูพลอย')).toBeVisible()
  await page.getByRole('button', { name: 'ส่งข้อความ', exact: true }).click()

  await page.goto('./#/teacher/messages?id=chat-fah')
  const thread = page.getByRole('log', { name: 'ประวัติข้อความ' })
  await expect(thread).toContainText('เป็นช่วงเงียบ ๆ')
  await expect(thread).not.toContainText('ที่อยากเก็บให้ตัวเอง')
  await expect(thread).not.toContainText('ท้องฟ้าหลังเลิกเรียน')

  await page.goto('./#/student/settings?tab=privacy')
  await page.getByText('ข้อความจากบันทึกที่เลือก', { exact: true }).click()
  await page.getByRole('button', { name: 'ยกเลิกการแชร์', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'ยกเลิกการแชร์', exact: true }).click()

  await page.goto('./#/teacher/messages?id=chat-fah')
  await expect(thread).toContainText('รายการแบ่งปันนี้ไม่สามารถเปิดได้')
  await expect(thread).not.toContainText('เป็นช่วงเงียบ ๆ')
})

test('blocks identical booking times and lets the student accept a teacher-proposed time', async ({ page }) => {
  await page.goto('./#/student/appointments?new=1&request=request-fah')
  const available = page.getByLabel('ช่วงเวลาที่ว่าง')
  const date = await page.getByLabel('วันที่นัดหมาย').inputValue()
  const option = await available.locator('option:not([disabled]):not([value=""])').first().getAttribute('value')
  expect(option).toBeTruthy()
  await available.selectOption(option!)
  await page.getByRole('button', { name: 'ส่งคำขอนัดหมาย' }).click()
  await expect(page.getByText('รอยืนยัน', { exact: true })).toBeVisible()
  const appointmentId = new URLSearchParams(page.url().split('?')[1]).get('id')
  expect(appointmentId).toBeTruthy()

  await page.goto('./#/teacher/appointments?new=1&request=request-fah')
  await page.getByLabel('วันที่นัดหมาย').fill(date)
  await page.getByLabel('เวลานัดหมาย').fill(option!)
  await page.getByRole('button', { name: 'ยืนยันการสร้างนัดหมาย' }).click()
  await expect(page.getByRole('alert')).toContainText('ช่วงเวลานี้มีการจองแล้ว')

  await page.goto('./#/teacher/appointments?id=' + appointmentId)
  await page.getByRole('link', { name: 'เสนอเวลาใหม่' }).click()
  await page.getByLabel('เวลานัดหมาย').fill('18:45')
  await page.getByRole('button', { name: 'ส่งเวลาใหม่ในสาธิต' }).click()
  await expect(page.getByText('เสนอเวลาใหม่', { exact: true }).first()).toBeVisible()
  await page.goto('./#/student/notifications')
  await page.getByRole('link', { name: /การนัดหมาย: เสนอเวลาใหม่/ }).click()
  await page.getByRole('button', { name: 'ยืนยันนัดหมาย' }).click()
  await expect(page.getByText('ยืนยันแล้ว', { exact: true })).toBeVisible()
  await expect(page.locator('.wf-review')).toContainText('18:45 น.')
})

test('keeps the mobile chat composer in view and opens the conversation picker on demand', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 860 })
  await page.goto('./#/student/messages?id=chat-fah')
  const picker = page.getByRole('button', { name: 'เลือกบทสนทนา' })
  await expect(page.getByLabel('พิมพ์ข้อความ')).toBeInViewport()
  await expect(page.getByLabel('ค้นหาชื่อคุณครู')).not.toBeVisible()
  await picker.click()
  await expect(page.getByLabel('ค้นหาชื่อคุณครู')).toBeVisible()
  await page.getByRole('link', { name: /ครูพลอย/ }).click()
  await expect(picker).toHaveAttribute('aria-expanded', 'false')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})
