test('loads deep links and bundled assets and restores seed data on refresh', async ({ page }) => {
  const failures: string[] = []
  page.on('response', response => { if (response.status() >= 400) failures.push(response.url()) })
  await page.goto('./')
  await expect(page.getByAltText(/นักเรียนและครูคุยกันบนสะพาน/)).toBeVisible()
  expect(await page.getByAltText(/นักเรียนและครูคุยกันบนสะพาน/).evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0)
  expect(await page.evaluate(async () => (await document.fonts.load('500 15px "Noto Sans Thai"', 'ภาษาไทย')).length)).toBeGreaterThan(0)
  await page.goto('./#/student/emotions?emotion=กังวล')
  await clickButton(page, 'บันทึกเช็กอิน')
  await expect(page.getByText('บันทึกเช็กอินแล้ว', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page).toHaveURL(/#\/student\/emotions/)
  await expect(page.getByText('บันทึกเช็กอินแล้ว', { exact: true })).toHaveCount(0)
  await page.goto('./#/student/dashboard')
  await expect(main(page).getByText('วันนี้บันทึกแล้ว', { exact: false })).toHaveCount(0)
  expect(failures).toEqual([])
})

for (const width of [375, 390, 768, 1440]) {
  test(`keeps the main views within ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    for (const route of ['/', '/select-role', '/student/dashboard', '/student/emotion-decoder', '/student/drawing', '/student/messages?id=chat-fah', '/teacher/dashboard', '/teacher/reports']) {
      await page.goto('./#' + route)
      await expect(main(page).getByRole('heading', { level: 1 }).first()).toBeVisible()
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
      expect(overflow, route).toBeLessThanOrEqual(1)
    }
    if (width < 620) await expect(page.getByRole('navigation', { name: 'เมนูด่วน' })).toBeVisible()
  })
}
